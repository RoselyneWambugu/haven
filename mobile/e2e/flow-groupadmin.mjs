// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-groupadmin.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8105)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
const login = async (name) => {
  await page.waitForTimeout(600) // let the last change reach storage before reloading
  await page.goto('http://localhost:8105/admin/sign-in')
  await page.waitForTimeout(1500)
  if (await tid('admin-sign-out').count()) await tid('admin-sign-out').click()
  await tid('admin-sign-in').waitFor()
  await tid(`staff-${name}`).click()
  await tid('mfa-code').fill('135790')
  await tid('admin-sign-in-go').click()
  await tid('admin-overview').waitFor()
}
let noticeId = null
const flush = () => page.waitForTimeout(900)
const body = async () => page.locator('body').innerText()

await page.goto('http://localhost:8105/welcome')
await page.waitForTimeout(1800)
await step('member-setup', async () => {
  await tid('get-started').click()
  for (const id of ['consent-terms', 'consent-privacy', 'consent-guidelines', 'consent-screening']) await tid(id).click()
  await tid('consent-continue').click()
  await tid('reg-name').fill('Amina Otieno')
  await tid('reg-phone').fill('0712 345 678')
  await tid('reg-dob').fill('14/03/1998')
  await tid('register-continue').click()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('pen-input').fill('BrightFern')
  await tid('pen-continue').click()
  await tid('finish').click()
  await tid('home').waitFor()
  await page.evaluate(() => window.__echo.demo.grantPlan('monthly'))
})
await step('moderators-see-group-chats-but-cannot-schedule', async () => {
  await login('T. Njeri')
  await tid('anav-groups').click()
  await tid('admin-groups').waitFor()
  await tid('people').waitFor()
  if (await tid('schedule').count()) throw new Error('a moderator should not see the schedule form')
})
await step('a-clinical-reviewer-schedules-a-group-chat', async () => {
  await login('Dr. K. Mwende')
  await tid('anav-groups').click()
  await tid('admin-groups').waitFor()
  await tid('g-create').click()
  await page.getByText(/at least 8 characters/).waitFor()
  await tid('g-topic').fill('Coping with a new diagnosis')
  await tid('g-blurb').fill('A gentle hour for people who have just had a diagnosis and want to talk.')
  await tid('g-day-1').click()
  await tid('g-hour-16').click()
  await shot('190-schedule')
  await tid('g-create').click()
  await tid('g-done').waitFor()
  await page.getByText('Coping with a new diagnosis').first().waitFor()
  await shot('191-scheduled')
  await page.waitForTimeout(800)
})
await step('a-member-signs-up-then-it-is-cancelled', async () => {
  const id = await page.evaluate(() => JSON.parse(localStorage.getItem('echo.demo.v1')).groupChats.find((g) => g.topic === 'Coping with a new diagnosis').id)
  await page.evaluate((i) => window.__echo.groups.register(i), id)
  await page.waitForTimeout(800)
  await login('Dr. K. Mwende')
  await tid('anav-groups').click()
  await tid(`cancel-${id}`).click()
  await tid('cancel-confirm').click()
  await page.getByText('A reason is required.').waitFor()
  await tid('cancel-reason').fill('The facilitator is unwell')
  await tid('cancel-confirm').click()
  await page.getByText('Cancelled by Dr. K. Mwende').waitFor()
  await shot('192-cancelled')
  await page.waitForTimeout(800)
  await page.goto(`http://localhost:8105/group-chats/${id}`)
  await tid('group-cancelled').waitFor()
  const n = await page.evaluate(() => JSON.parse(localStorage.getItem('echo.demo.v1')).notifications.filter((x) => x.title === 'Your group chat was cancelled').length)
  if (n !== 1) throw new Error('the member should be told')
})
await step('a-moderator-removes-people-from-an-open-chat', async () => {
  await page.evaluate(() => window.__echo.demo.startNextGroupChat())
  await page.waitForTimeout(500)
  await page.evaluate(() => window.__echo.demo.advanceClock(3))
  await page.waitForTimeout(900)
  await login('T. Njeri')
  await tid('anav-groups').click()
  await tid('people').waitFor()
  await tid('remove-WarmLantern').click()
  await tid('remove-confirm').click()
  await page.getByText('A reason is required.').waitFor()
  await tid('remove-reason').fill('Kept asking others for their numbers')
  await tid('remove-confirm').click()
  await page.getByText('WarmLantern · removed').waitFor()
  await tid('remove-BrightFern').click()
  await tid('remove-reason').fill('Repeated unkind messages to others')
  await shot('193-remove')
  await tid('remove-confirm').click()
  await page.getByText('BrightFern · removed').waitFor()
  await page.waitForTimeout(800)
  const id = await page.evaluate(() => JSON.parse(localStorage.getItem('echo.demo.v1')).groupChats.find((g) => g.removed?.length).id)
  await page.goto(`http://localhost:8105/group-chats/${id}`)
  await tid('group-removed').waitFor()
  await page.getByText('Message removed by a moderator').first().waitFor()
  await shot('194-removed-member')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
