// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-forum.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8097)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }

await page.goto('http://localhost:8097/')
await page.waitForTimeout(1800)
await step('register', async () => {
  await tid('get-started').click()
  await tid('who-member').click()
  for (const id of ['consent-terms', 'consent-privacy', 'consent-guidelines', 'consent-screening']) await tid(id).click()
  await tid('consent-continue').click()
  await tid('reg-name').fill('Amina Otieno')
  await tid('reg-phone').fill('0712 345 678')
  await tid('reg-dob').fill('14/03/1998')
  await tid('register-continue').click()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('pen-input').fill('BrightFern')
  await tid('pen-continue').click()
  await tid('finish').click()
  await tid('home').waitFor()
})
await step('the-community-needs-a-plan', async () => {
  await tid('tab-forum').click()
  await tid('forum').waitFor()
  await tid('plan-gate').waitFor()
  await shot('19-community-locked')
  if (await tid('forum-new').count()) throw new Error('posting should be locked')
  await page.evaluate(() => window.__echo.demo.grantPlan('monthly'))
  await page.waitForTimeout(300)
  await tid('plan-gate').waitFor({ state: 'detached' })
})
await step('feed', async () => {
  await tid('tab-forum').click()
  await tid('forum').waitFor()
  await shot('20-forum-feed')
  await tid('topic-Grief').click()
  await page.waitForTimeout(200)
  const t = await page.locator('body').innerText()
  if (/Small win today/.test(t)) throw new Error('topic filter did not filter')
})
await step('post-detail', async () => {
  await tid('topic-Grief').click()
  await tid('post-f4').click()
  await tid('post-detail').waitFor()
  await shot('21-post-detail')
  await tid('support').click()
  await tid('comment-input').fill('Message me on 0712345678')
  await page.waitForTimeout(200)
  if ((await tid('comment-send').getAttribute('aria-disabled')) !== 'true') throw new Error('send should be disabled for a phone number')
  await shot('22-comment-blocked')
  await tid('comment-input').fill('Thank you for sharing this')
  await tid('comment-send').click()
  await page.waitForTimeout(300)
  if (!/Thank you for sharing this/.test(await page.locator('body').innerText())) throw new Error('comment missing')
})
await step('composer', async () => {
  await page.getByRole('button', { name: 'Back' }).click()
  await tid('forum-new').click()
  await tid('post-title').fill('Feeling stretched at Strathmore University')
  await tid('post-body').fill('I have been feeling stretched at Strathmore University and cannot sleep well at all.')
  await shot('23-composer')
  await tid('post-submit').click()
  await tid('identify-sheet').waitFor()
  await shot('24-identify-warning')
  await tid('post-anyway').click()
  await tid('my-posts').waitFor()
  await shot('25-my-posts-pending')
})
await step('replies-arrive-and-notify', async () => {
  // Quiet hours (22:00 to 07:00 East Africa Time) hold notifications back, so switch them off to make this flow the same at any time of day.
  await page.evaluate(() => window.__echo.auth.setSettings({ quietHours: false }))
  // The post goes live after about 15 s, a peer replies about 20 s later and a therapist about 25 s after that.
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('echo.demo.v1') || '{}').notifications?.filter((n) => n.title === 'New reply to your post').length === 2, null, { timeout: 90000 })
  await page.goto('http://localhost:8097/notifications')
  await tid('notification-centre').waitFor()
  await page.getByText('New reply to your post').first().click()
  await tid('post-detail').waitFor()
  await page.getByText('General information, not treatment or advice for you.').waitFor()
  await shot('26-post-with-replies')
})
await step('gossip', async () => {
  await page.goto('http://localhost:8097/forum')
  await tid('forum').waitFor()
  await tid('view-gossip').click()
  await tid('gossip-rules').waitFor()
  await shot('23-gossip')
  if (!/talking/i.test(await page.locator('body').innerText())) throw new Error('starter gossip missing')
  await tid('gossip-new').click()
  await tid('gossip-new-screen').waitFor()
  await tid('gossip-title').fill('Big news in the estate')
  await tid('gossip-body').fill('They say Wanjiku is moving out of the estate next month and nobody knows why.')
  await tid('gossip-names').waitFor()
  await shot('24-gossip-name-warning')
  await tid('gossip-submit').click()
  await page.waitForTimeout(300)
  if (!/looks like a name/.test(await page.locator('body').innerText())) throw new Error('a name should be stopped')
  await tid('gossip-body').fill('They say the matatu fares went up on Monday and nobody knows why.')
  await tid('gossip-submit').click()
  await tid('post-detail').waitFor()
  await tid('gossip-no-replies').waitFor()
  await page.getByRole('button', { name: 'Back' }).click()
  await tid('view-gossip').click()
  await tid('post-g1').click()
  await tid('post-detail').waitFor()
  await tid('gossip-no-replies').waitFor()
  if (await tid('comment-input').count()) throw new Error('gossip should take no replies')
  await tid('support').click()
  await shot('25-gossip-post')
})
await step('events', async () => {
  await page.goto('http://localhost:8097/forum')
  await tid('forum').waitFor()
  await tid('view-events').click()
  await tid('event-ev-sleep').waitFor()
  await shot('27-events')
  await tid('event-ev-sleep').click()
  await tid('event-detail').waitFor()
  const before = Number((await tid('event-interested').innerText()).match(/(\d+)\s*$/)[1])
  await tid('event-interested').click()
  await page.waitForTimeout(300)
  const after = Number((await tid('event-interested').innerText()).match(/(\d+)\s*$/)[1])
  if (after !== before + 1) throw new Error(`the count should go up by one (${before} to ${after})`)
  await shot('28-event-interested')
  await tid('event-interested').click()
  await page.waitForTimeout(300)
  const back = Number((await tid('event-interested').innerText()).match(/(\d+)\s*$/)[1])
  if (back !== before) throw new Error('taking it back should lower the count')
})
await step('event-reminder', async () => {
  await page.goto('http://localhost:8097/events/ev-sleep')
  await tid('event-detail').waitFor()
  await tid('event-interested').click()
  await page.waitForTimeout(300)
  // move to 50 minutes before it starts
  await page.evaluate(() => {
    const s = JSON.parse(localStorage.getItem('echo.demo.v1'))
    const e = s.events.find((x) => x.id === 'ev-sleep')
    window.__echo.demo.advanceClock(Math.floor((e.startsAt - 50 * 60000 - Date.now()) / 60000))
  })
  // stay inside the app: a page load would reset the clock that was moved on
  await page.evaluate(() => { window.history.pushState({}, '', '/notifications'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await tid('notification-centre').waitFor()
  await page.getByText('An event you’re interested in is coming up').waitFor()
  await shot('29-event-reminder')
})
await step('polls', async () => {
  await page.goto('http://localhost:8097/forum')
  await tid('forum').waitFor()
  await tid('view-polls').click()
  await tid('poll-pl1').waitFor()
  const card = tid('poll-pl1')
  if (/\d+%/.test(await card.innerText())) throw new Error('counts should be hidden before voting')
  await shot('30-polls')
  await tid('poll-pl1-option-1').click()
  await page.waitForTimeout(300)
  if (!/\d+%/.test(await card.innerText())) throw new Error('the shares should show after voting')
  if (!/\d+ votes/.test(await card.innerText())) throw new Error('the vote count should show after voting')
  await shot('31-poll-voted')
  await tid('poll-new').click()
  await tid('poll-new-screen').waitFor()
  await tid('poll-question').fill('Should Wanjiku quit her job this year?')
  await tid('poll-option-0').fill('Yes')
  await tid('poll-option-1').fill('No')
  await tid('poll-problem').waitFor()
  await shot('32-poll-name-warning')
  await tid('poll-question').fill('What is the best way to wind down?')
  await tid('poll-add-option').click()
  await tid('poll-option-0').fill('A long walk')
  await tid('poll-option-1').fill('Music')
  await tid('poll-option-2').fill('Sleep')
  await tid('poll-submit').click()
  await tid('post-detail').waitFor()
  await tid('poll-no-replies').waitFor()
  if (await tid('comment-input').count()) throw new Error('a poll should take no replies')
  await shot('33-poll-asked')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
