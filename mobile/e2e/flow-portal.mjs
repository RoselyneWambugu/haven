// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-portal.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8093)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
await page.goto('http://localhost:8093/')
await page.waitForTimeout(1800)
await step('sign-in', async () => {
  await tid('therapist-link').click()
  await tid('portal-sign-in').waitFor()
  await shot('60-sign-in')
  await tid('portal-demo-sign-in').click()
  await tid('portal-today').waitFor()
  const sb = await tid('sidebar').boundingBox()
  const main = await tid('portal-today').boundingBox()
  if (!sb || !main || sb.x + sb.width > main.x + 1 || sb.height < 400) throw new Error('the navigation should be a sidebar on the left')
  await shot('61-today')
})
await step('join-live-notes', async () => {
  await page.evaluate(() => window.__echo.demo.advanceClock(5))
  await page.locator('[data-testid^="join-"]').first().click()
  await tid('portal-live').waitFor()
  await tid('live-notes').fill('Sleep improved. Exam anxiety remains.')
  await page.waitForTimeout(900)
  await shot('62-live')
})
await step('concern', async () => {
  await tid('live-concern').click()
  await tid('concern').waitFor()
  if ((await tid('concern-send').getAttribute('aria-disabled')) !== 'true') throw new Error('send should wait for the danger question')
  await tid('danger-no').click()
  await shot('63-concern')
  await tid('concern-send').click()
  await tid('concern-sent').waitFor()
  await shot('64-concern-sent')
  await tid('concern-done').click()
})
await step('wrap-up', async () => {
  await tid('live-end').click()
  await tid('wrap-up').waitFor()
  await shot('65-wrap-up')
  await tid('wrap-save').click()
  await tid('portal-sessions').waitFor()
  await shot('66-sessions')
})
await step('inbox-blocks-contact', async () => {
  await tid('nav-inbox').click()
  await tid('portal-inbox').waitFor()
  await tid('inbox-input').fill('Call me on 0712345678')
  await tid('inbox-send').click()
  await tid('inbox-block-reason').waitFor()
  await shot('67-inbox-blocked')
  await tid('inbox-input').fill('See you Tuesday, take care.')
  await tid('inbox-send').click()
  await page.waitForTimeout(300)
  if (!/See you Tuesday/.test(await page.locator('body').innerText())) throw new Error('reply missing')
})
await step('calendar', async () => {
  await tid('nav-calendar').click()
  await tid('portal-calendar').waitFor()
  await tid('cell-3-14').click()
  await tid('pause-new').click()
  await shot('68-calendar')
})
await step('profile-refuses-contact', async () => {
  await tid('nav-profile').click()
  await tid('portal-profile').waitFor()
  await tid('profile-bio').fill('I help people heal. Email me at amina@example.com for private sessions.')
  await tid('profile-save').click()
  await page.waitForTimeout(200)
  await shot('69-profile-refused')
  if (/Published/.test(await page.locator('body').innerText())) throw new Error('should not publish contact details')
  await tid('profile-bio').fill('I help people feel heard and build calm routines for sleep and stress.')
  await tid('profile-save').click()
  await page.waitForTimeout(200)
  if (!/Published/.test(await page.locator('body').innerText())) throw new Error('profile not published')
})
await step('forum-no-soliciting', async () => {
  await tid('nav-forum').click()
  await tid('portal-forum').waitFor()
  await page.locator('[data-testid^="reply-"]').first().click()
  await tid('fpost-reply').fill('Book a session with me and we can work on this together.')
  await tid('fpost-send').click()
  await page.waitForTimeout(200)
  await shot('70-forum-refused')
  if (!/can’t invite people/.test(await page.locator('body').innerText())) throw new Error('solicit warning missing')
})
await step('earnings-and-payout', async () => {
  await tid('nav-earnings').click()
  await tid('portal-earnings').waitFor()
  await shot('71-earnings')
  await tid('change-payout').click()
  await tid('payout-code').fill('246810')
  await tid('payout-verify').click()
  await tid('payout-method').fill('M-Pesa 0700 ••• 000')
  await tid('payout-save').click()
  await page.waitForTimeout(300)
  if (!/0700/.test(await page.locator('body').innerText())) throw new Error('payout not changed')
})
await step('apply-flow', async () => {
  await tid('portal-sign-out').click()
  await tid('portal-sign-in').waitFor()
  await page.evaluate(() => window.__echo.demo.reset())
  await page.waitForTimeout(500)
  await tid('portal-apply').click()
  await tid('apply').waitFor()
  await tid('apply-name').fill('Dr. Grace Wanjiru')
  await tid('apply-licence').fill('5588')
  await tid('apply-submit').click()
  await page.waitForTimeout(200)
  if (!/Add your licence/.test(await page.locator('body').innerText())) throw new Error('missing-docs message not shown')
  for (const id of ['doc-licence', 'doc-id', 'doc-qualification', 'consent-public', 'consent-conduct']) await tid(id).click()
  await tid('apply-submit').click()
  await tid('apply-status').waitFor()
  await tid('advance-review').click()
  await tid('more-info').waitFor()
  await shot('72-more-info')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
