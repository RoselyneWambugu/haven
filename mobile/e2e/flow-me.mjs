// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-me.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8094)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
await page.goto('http://localhost:8094/')
await page.waitForTimeout(1800)
await step('register', async () => {
  await tid('get-started').click()
  for (const id of ['consent-terms', 'consent-privacy', 'consent-guidelines', 'consent-screening']) await tid(id).click()
  await tid('consent-continue').click()
  await tid('reg-name').fill('Amina Otieno')
  await tid('reg-phone').fill('0712 345 678')
  await tid('reg-dob').fill('14/03/1998')
  await tid('register-continue').click()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('pen-input').fill('BrightFern')
  await tid('pen-continue').click()
  await tid('finish').click()
  await tid('home').waitFor()
})
await step('me-and-profiles', async () => {
  await tid('open-me').click()
  await tid('me').waitFor()
  await shot('50-me')
  await tid('me-profiles').click()
  await tid('profiles').waitFor()
  await shot('51-public')
  await page.getByText('Private', { exact: true }).click()
  await tid('verify-private').click()
  await tid('otp').waitFor()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('private-details').waitFor()
  await shot('52-private')
  const body = await page.locator('body').innerText()
  if (!/Amina Otieno/.test(body)) throw new Error('private name not shown')
})
await step('pen-name-change-limit', async () => {
  await page.getByText('Public', { exact: true }).click()
  await tid('edit-pen-name').click()
  await tid('new-pen-name').fill('CalmRiver')
  await tid('save-pen-name').click()
  await page.waitForTimeout(200)
  await tid('edit-pen-name').click()
  await tid('new-pen-name').fill('OtherName')
  await tid('save-pen-name').click()
  await page.waitForTimeout(200)
  if (!/change your pen name again in/.test(await page.locator('body').innerText())) throw new Error('limit message missing')
  await shot('53-pen-limit')
})
await step('settings', async () => {
  await page.goto('http://localhost:8094/settings/security')
  await page.waitForTimeout(1500)
  await tid('security').waitFor()
  await shot('54-security')
  await page.goto('http://localhost:8094/settings/notifications')
  await page.waitForTimeout(1500)
  await tid('notifications').waitFor()
  await shot('55-notifications')
})
await step('standing-appeal', async () => {
  await page.evaluate(() => window.__echo.demo.addNotice())
  await page.waitForTimeout(1000)
  await page.goto('http://localhost:8094/standing')
  await page.waitForTimeout(1500)
  await page.locator('[data-testid^="appeal-n"]').first().click()
  await tid('appeal-text').fill('I was sharing a general tip, not my number')
  await tid('appeal-send').click()
  await page.waitForTimeout(300)
  await shot('56-appeal')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
