// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-book.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8096)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
await page.goto('http://localhost:8096/')
await page.waitForTimeout(1800)
await step('register', async () => {
  await tid('get-started').click()
  for (const id of ['consent-terms', 'consent-privacy', 'consent-guidelines', 'consent-screening']) await tid(id).click()
  await tid('consent-continue').click()
  await tid('reg-name').fill('Amina Otieno')
  await tid('reg-phone').fill('0712 345 678')
  await tid('reg-dob').fill('14/03/1998')
  await tid('register-continue').click()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('pen-input').fill('BrightFern')
  await tid('pen-continue').click()
  await tid('finish').click()
  await tid('home').waitFor()
  await page.evaluate(() => window.__echo.demo.showPrices(true))
})
await step('plan-checkout', async () => {
  await tid('home-see-plans').click()
  await tid('plans').waitFor()
  await shot('30-plans')
  await tid('plans-continue').click()
  await tid('checkout').waitFor()
  await shot('31-checkout')
  await page.evaluate(() => window.__echo.demo.failNextPayment(true))
  await tid('pay').click()
  await tid('checkout-waiting').waitFor()
  await shot('32-waiting')
  await tid('checkout-failed').waitFor({ timeout: 8000 })
  await shot('33-failed')
  await tid('checkout-retry').click()
  await tid('checkout-success').waitFor({ timeout: 8000 })
  await shot('34-success')
  await tid('checkout-done').click()
  await tid('match-searching').waitFor()
  await page.getByRole('button', { name: 'Stop looking' }).click()
})
await step('directory-and-profile', async () => {
  await tid('tab-therapists').click()
  await tid('therapists').waitFor()
  await shot('35-directory')
  await tid('dir-search').fill('grief')
  await page.waitForTimeout(200)
  if (/James Mwangi/.test(await page.locator('body').innerText())) throw new Error('search did not filter')
  await tid('therapist-t-amina').click()
  await tid('therapist-profile').waitFor()
  await shot('36-profile')
})
let sessionId = ''
await step('book-and-pay', async () => {
  await tid('book').click()
  await tid('book-screen').waitFor()
  await page.locator('[data-testid^="slot-"]').first().click()
  await shot('37-book')
  await tid('book-continue').click()
  await tid('checkout').waitFor()
  await tid('pay').click()
  await tid('checkout-success').waitFor({ timeout: 8000 })
  await tid('checkout-done').click()
  await tid('session-detail').waitFor()
  sessionId = page.url().split('/').pop().split('?')[0]
  await shot('38-session')
})
await step('reschedule-and-cancel', async () => {
  await tid('cancel-session').click()
  await tid('session-cancel').waitFor()
  await shot('39-cancel')
  await tid('cancel-confirm').click()
  await tid('change-done').waitFor()
  await tid('change-ok').click()
})
await step('report-a-therapist-concern', async () => {
  await page.evaluate((id) => window.__echo.sessions.end(id), sessionId)
  await page.waitForTimeout(700)
  await page.goto(`http://localhost:8096/sessions/${sessionId}`)
  await tid('session-concern').click()
  await tid('concern-sheet').waitFor()
  await tid('concern-therapist-boundaries').click()
  if (!(await tid('concern-send').isDisabled())) throw new Error('a note should be needed')
  await tid('concern-note').fill('They asked where I live and I did not feel safe')
  await shot('39b-concern')
  await tid('concern-send').click()
  await page.getByText('We received your concern').waitFor()
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
