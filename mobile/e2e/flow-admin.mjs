// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-admin.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8092)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
const login = async (name) => {
  await page.waitForTimeout(600) // let the last change reach storage before reloading
  await page.goto('http://localhost:8092/admin/sign-in')
  await page.waitForTimeout(1500)
  if (await tid('admin-sign-out').count()) await tid('admin-sign-out').click()
  await tid('admin-sign-in').waitFor()
  await tid(`staff-${name}`).click()
  await tid('mfa-code').fill('135790')
  await tid('admin-sign-in-go').click()
  await tid('admin-overview').waitFor()
}
let noticeId = null
const flush = () => page.waitForTimeout(900)
const body = async () => page.locator('body').innerText()

await page.goto('http://localhost:8092/')
await page.waitForTimeout(1800)
await step('member-setup', async () => {
  await tid('get-started').click()
  for (const id of ['consent-terms', 'consent-privacy', 'consent-guidelines', 'consent-screening']) await tid(id).click()
  await tid('consent-continue').click()
  await tid('reg-name').fill('Amina Otieno')
  await tid('reg-phone').fill('0712 345 678')
  await tid('reg-dob').fill('14/03/1998')
  await tid('register-continue').click()
  const code = (await tid('demo-code').innerText()).match(/(\d{6})/)[1]
  await tid('otp-input').fill(code)
  await tid('pen-input').fill('BrightFern')
  await tid('pen-continue').click()
  await tid('finish').click()
  await tid('home').waitFor()
  await page.evaluate(() => {
    window.__echo.report.submit({ target: 'member', targetId: 'p-rainy', reason: 'threats', note: 'They said I would regret ignoring them' })
    window.__echo.demo.addNotice()
  })
  await flush()
  noticeId = await page.evaluate(() => JSON.parse(localStorage.getItem('echo.demo.v1')).account.notices[0].id)
  await page.evaluate((id) => window.__echo.account.appeal(id, 'I was only quoting what they sent me'), noticeId)
  await flush()
})
await step('sign-in-needs-mfa', async () => {
  await page.goto('http://localhost:8092/admin/sign-in')
  await tid('admin-sign-in').waitFor()
  await tid('staff-T. Njeri').click()
  await tid('mfa-code').fill('000000')
  await tid('admin-sign-in-go').click()
  await page.waitForTimeout(200)
  if (!/doesn’t match/.test(await body())) throw new Error('wrong code should be refused')
  await shot('80-sign-in')
  await tid('mfa-code').fill('135790')
  await tid('admin-sign-in-go').click()
  await tid('admin-overview').waitFor()
  await shot('81-overview')
})
await step('case-queue', async () => {
  await tid('anav-cases').click()
  await tid('admin-cases').waitFor()
  await shot('82-cases')
  const t = await body()
  if (!/C-1049/.test(t) || !/C-1042/.test(t)) throw new Error('seed cases missing')
  if (!/Threat/.test(t)) throw new Error('member report did not become a case')
  await tid('cf-S1').click()
  await page.waitForTimeout(200)
  if (/C-1042/.test(await body())) throw new Error('S1 filter should hide S2')
})
await step('case-reveal-and-decide', async () => {
  await tid('cf-all').click()
  await tid('case-C-1042').click()
  await tid('admin-case').waitFor()
  const before = await page.locator('[data-testid="ev-e2"]').innerText()
  if (/number/.test(before)) throw new Error('evidence should be blurred')
  await tid('reveal-e2').click()
  await page.waitForTimeout(200)
  if (!/number/.test(await tid('ev-e2').innerText())) throw new Error('reveal did not show text')
  await shot('83-case')
  await tid('submit-decision').click()
  await page.waitForTimeout(200)
  if (!/reason is required/.test(await body())) throw new Error('decision without reason should be refused')
  await tid('decision-reason').fill('Second report in a week, soliciting contact details')
  await tid('submit-decision').click()
  await page.waitForTimeout(300)
  if (!/Decided: strike/.test(await body())) throw new Error('decision not recorded')
})
await step('break-glass-needs-second-person', async () => {
  await tid('anav-cases').click()
  await tid('case-C-1046').click()
  await tid('open-break-glass').click()
  await tid('bg-justification').fill('too short')
  await tid('bg-request').click()
  await page.waitForTimeout(200)
  if (!/Explain why/.test(await body())) throw new Error('short justification should be refused')
  await shot('84-break-glass')
  await tid('bg-justification').fill('They said they would hurt someone tonight')
  await tid('bg-request').click()
  await tid('bg-status').waitFor()
  if (!/can’t approve your own/.test(await body())) throw new Error('should wait for a second person')
  await flush()
})
await step('clinical-approves', async () => {
  await login('Dr. K. Mwende')
  await tid('bg-approvals').waitFor()
  await shot('85-approvals')
  await page.locator('[data-testid^="bg-approve-"]').first().click()
  await flush()
  await login('T. Njeri')
  await tid('anav-cases').click()
  await tid('case-C-1046').click()
  await tid('bg-view').click()
  await tid('bg-profile').waitFor()
  await shot('86-private-profile')
})
await step('user-action-changes-member', async () => {
  await tid('anav-users').click()
  await tid('user-BrightFern').click()
  await tid('act-suspend').click()
  await tid('user-act-confirm').click()
  await page.waitForTimeout(200)
  await tid('user-act-reason').fill('Repeated harassment of matches')
  await tid('user-act-confirm').click()
  await page.waitForTimeout(400)
  const standing = await page.evaluate(() => JSON.parse(localStorage.getItem('echo.demo.v1') ?? '{}').account?.standing)
  if (standing !== 'paused') throw new Error('member should now be paused, got ' + standing)
  await shot('87-user')
})
await step('appeal-needs-another-reviewer', async () => {
  await tid('anav-appeals').click()
  await tid('admin-appeals').waitFor()
  await page.locator('[data-testid^="appeal-"]').first().click()
  await tid('admin-appeal').waitFor()
  if (!/You made the original decision/.test(await body())) throw new Error('conflict banner missing')
  await shot('88-appeal')
  await login('A. Mwangi')
  await tid('anav-appeals').click()
  await page.locator('[data-testid^="appeal-A-n"]').first().click()
  await tid('appeal-explanation').fill('The context shows no violation.')
  await tid('appeal-decide').click()
  await page.waitForTimeout(900)
  const notice = await page.evaluate((id) => JSON.parse(localStorage.getItem('echo.demo.v1')).account.notices.find((n) => n.id === id), noticeId)
  if (notice.appeal !== 'upheld' && notice.appeal !== 'reduced' && notice.appeal !== 'overturned') throw new Error('member notice not updated: ' + notice.appeal)
})
await step('billing-role', async () => {
  await login('J. Otieno')
  if (await tid('anav-cases').count()) throw new Error('billing should not see Cases')
  await tid('anav-billing').click()
  await tid('admin-billing').waitFor()
  await tid('approve-R-310').click()
  await page.waitForTimeout(200)
  await shot('89-billing')
  if (!/Approved by J. Otieno/.test(await body())) throw new Error('refund not approved')
})
await step('therapist-verification', async () => {
  await login('Dr. K. Mwende')
  await tid('anav-therapists').click()
  await tid('applicant-T-88').click()
  await tid('verify-message').fill('Welcome to Echo.')
  await tid('verify-submit').click()
  await page.waitForTimeout(200)
  if (!/Tick every check/.test(await body())) throw new Error('should require every check')
  for (const id of ['chk-name', 'chk-licence', 'chk-expiry', 'chk-qualification']) await tid(id).click()
  await shot('90-verify')
  await tid('verify-submit').click()
  await tid('admin-therapists').waitFor()
})
await step('policy-two-admins', async () => {
  await login('S. Kamau')
  await tid('anav-moderation').click()
  await tid('policy-expiry').fill('60')
  await tid('propose-policy').click()
  await page.waitForTimeout(200)
  await shot('91-moderation')
  await tid('approve-policy').click()
  await page.waitForTimeout(200)
  if (!/second admin has to approve/.test(await body())) throw new Error('self-approval should be refused')
  await flush()
  await login('R. Achieng')
  await tid('anav-moderation').click()
  await tid('approve-policy').click()
  await page.waitForTimeout(300)
  if (!/60 days/.test(await tid('strike-policy').innerText())) throw new Error('policy not changed')
})
await step('audit-log', async () => {
  await tid('anav-audit').click()
  await tid('admin-audit').waitFor()
  await shot('92-audit')
  const t = await body()
  for (const w of ['Viewed case content', 'Revealed message', 'Break-glass requested', 'Break-glass approved', 'Suspended user', 'Approved refund', 'Approved therapist']) {
    if (!t.includes(w)) throw new Error('audit entry missing: ' + w)
  }
  if (!(await tid('export-audit').count())) throw new Error('admin should see export')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
