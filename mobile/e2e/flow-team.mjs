// Onboards, grants a demo plan, matches with a peer, and exercises blocked-message handling in chat.
// Usage: node e2e/flow-team.mjs <webroot> <outdir>
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { serve } from './serve.mjs'

const [root, out] = process.argv.slice(2)
mkdirSync(out, { recursive: true })
const server = await serve(root, 8089)
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
const problems = []
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text().slice(0, 240)}`))
page.on('pageerror', (e) => problems.push(`pageerror: ${String(e).slice(0, 300)}`))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
const tid = (id) => page.locator(`[data-testid="${id}"]`)
const step = async (name, fn) => { try { await fn(); console.log('ok  ', name) } catch (e) { console.log('FAIL', name, String(e).split('\n')[0]); await shot(`FAIL-${name}`); console.log(problems.join('\n')); throw e } }
const body = async () => page.locator('body').innerText()
const BASE = 'http://localhost:8089'
const login = async (name) => {
  await page.waitForTimeout(700)
  await page.goto(`${BASE}/admin/sign-in`)
  await page.waitForTimeout(1500)
  if (await tid('admin-sign-out').count()) await tid('admin-sign-out').click()
  await tid('admin-sign-in').waitFor()
  await tid(`staff-${name}`).click()
  await tid('mfa-code').fill('135790')
  await tid('admin-sign-in-go').click()
  await page.waitForTimeout(500)
}

await page.goto(`${BASE}/`)
await page.waitForTimeout(1200)
await step('roles-screen-shows-the-table-and-team', async () => {
  await login('S. Kamau')
  await tid('anav-roles').click()
  await tid('admin-roles').waitFor()
  await shot('130-roles')
  const t = await body()
  for (const w of ['Everyone signs in with a second factor', 'View a member’s real identity', 'Issue refunds', 'T. Njeri', 'R. Achieng']) if (!t.includes(w)) throw new Error('missing: ' + w)
  for (const r of ['Moderator', 'Clinical reviewer', 'Support / Billing']) if (!(await tid('matrix').innerText()).includes(r)) throw new Error('matrix should show ' + r)
})

await step('adding-a-person-needs-a-second-admin', async () => {
  await tid('add-staff').click()
  await tid('new-staff-name').fill('N. Wafula')
  await tid('add-save').click()
  await tid('pending-staff').waitFor()
  await shot('131-pending')
  await tid('approve-staff').click()
  await page.waitForTimeout(300)
  if (!/second admin has to approve/.test(await body())) throw new Error('self-approval should be refused')
  await login('R. Achieng')
  await tid('anav-roles').click()
  await tid('approve-staff').click()
  await page.waitForTimeout(400)
  if (!(await tid('staff-N. Wafula').count())) throw new Error('new person should be on the team')
})

await step('the-new-person-can-sign-in-with-mfa-and-sees-only-their-role', async () => {
  await login('N. Wafula')
  await tid('admin-overview').waitFor()
  if (await tid('anav-roles').count() || await tid('anav-configuration').count()) throw new Error('a moderator should not see Roles or Config')
  if (!(await tid('anav-wellbeing').count())) throw new Error('moderators should see Wellbeing')
})

await step('heavy-cases-are-for-the-rota', async () => {
  await login('T. Njeri')
  await tid('anav-cases').click()
  await tid('case-C-1049').click()
  await tid('admin-case').waitFor()
  await tid('take-case').click()
  await page.waitForTimeout(300)
  if (!/heavy-queue rota/.test(await body())) throw new Error('T. Njeri is not on this week’s rota')
  await shot('132-not-on-rota')
  await login('A. Mwangi')
  await tid('anav-cases').click()
  await tid('case-C-1049').click()
  await tid('take-case').click()
  await page.waitForTimeout(300)
  if (!/Owner: A. Mwangi/.test(await body())) throw new Error('A. Mwangi is on the rota and should get the case')
})

await step('breaks-pause-revealing', async () => {
  await login('T. Njeri')
  await tid('anav-wellbeing').click()
  await tid('admin-wellbeing').waitFor()
  await shot('133-wellbeing')
  if (!/3 of 20/.test(await tid('exposure').innerText())) throw new Error('exposure should show 3 of 20')
  await tid('start-break').click()
  await page.waitForTimeout(300)
  if (!/on a break/i.test(await body())) throw new Error('break should be on')
  await tid('anav-cases').click()
  await tid('case-C-1042').click()
  await tid('admin-case').waitFor()
  await tid('reveal-e0').click()
  await page.waitForTimeout(300)
  if (!/on a break/.test(await body())) throw new Error('reveal should be refused during a break')
  await shot('134-break-on-case')
  await tid('anav-wellbeing').click()
  await tid('end-break').click()
})

await step('admin-sets-limits-and-a-break-is-suggested', async () => {
  await login('S. Kamau')
  await page.evaluate(() => window.__echo.team.setWellbeing({ dailyLimit: 20, breakEvery: 3, breakMinutes: 10 }))
  await login('T. Njeri')
  await tid('anav-cases').click()
  await tid('case-C-1042').click()
  await tid('admin-case').waitFor()
  for (const id of ['e0', 'e1', 'e2']) { await tid(`reveal-${id}`).click(); await page.waitForTimeout(250) }
  if (!/Time for a break\?/.test(await body())) throw new Error('a break should be suggested on the case page')
  await tid('anav-wellbeing').click()
  await tid('break-suggested').waitFor()
  await shot('135-suggested')
})

await step('the-rota-rotates', async () => {
  await login('S. Kamau')
  await tid('anav-wellbeing').click()
  await tid('rota').waitFor()
  await tid('rota-pick-A. Mwangi').click()
  await page.waitForTimeout(300)
  await tid('rota-pick-T. Njeri').click()
  await page.waitForTimeout(300)
  if (!/same people can’t work the heavy queue two weeks running/.test(await body())) throw new Error('rotation rule should be enforced')
  await shot('136-rota')
})

await step('support-and-handing-on', async () => {
  await login('T. Njeri')
  await tid('anav-wellbeing').click()
  await tid('ask-support').click()
  await page.waitForTimeout(300)
  if (!/check in with you/.test(await body())) throw new Error('support confirmation missing')
  await tid('anav-cases').click()
  await tid('case-C-1042').click()
  await tid('hand-on').click()
  await page.waitForTimeout(400)
  if (!(await tid('take-case').count())) throw new Error('case should be unassigned after handing on')
})

await step('clinical-reviewers-recommend-rather-than-sanction', async () => {
  await login('Dr. K. Mwende')
  await tid('anav-cases').click()
  await tid('case-C-1042').click()
  await tid('admin-case').waitFor()
  await page.getByText('Suspend', { exact: true }).click()
  await tid('decision-reason').fill('Repeated sexual advances toward a match')
  await tid('submit-decision').click()
  await page.waitForTimeout(300)
  await shot('137-recommend')
  if (!/recommends a sanction/.test(await body())) throw new Error('clinical reviewers should not apply sanctions')
})

await step('deactivating-someone-stops-sign-in', async () => {
  await login('S. Kamau')
  await tid('anav-roles').click()
  await tid('active-N. Wafula').click()
  await tid('approve-staff').waitFor()
  await login('R. Achieng')
  await tid('anav-roles').click()
  await tid('approve-staff').click()
  await page.waitForTimeout(500)
  await page.waitForTimeout(700)
  await page.goto(`${BASE}/admin/sign-in`)
  await page.waitForTimeout(1500)
  if (await tid('admin-sign-out').count()) await tid('admin-sign-out').click()
  await tid('staff-N. Wafula').click()
  await tid('mfa-code').fill('135790')
  await tid('admin-sign-in-go').click()
  await page.waitForTimeout(300)
  if (!/deactivated/.test(await body())) throw new Error('a deactivated account should not sign in')
})

await step('it-is-all-in-the-audit-log', async () => {
  await login('S. Kamau')
  await tid('anav-audit').click()
  await tid('admin-audit').waitFor()
  const t = await body()
  for (const w of ['Proposed team change', 'Approved team change', 'Started a break', 'Asked for wellbeing support', 'Handed a case on', 'Took case']) if (!t.includes(w)) throw new Error('audit entry missing: ' + w)
  await shot('138-audit')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
