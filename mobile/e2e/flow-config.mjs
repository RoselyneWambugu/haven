await step('everything-is-in-the-audit-log', async () => {
  await tid('anav-audit').click()
  await tid('admin-audit').waitFor()
  const t = await body()
  for (const w of ['Added topic', 'Turned off feature', 'Proposed plan change', 'Approved plan change', 'Changed matching', 'Changed limits']) {
    if (!t.includes(w)) throw new Error('audit entry missing: ' + w)
  }
  await shot('120-audit')
})
await browser.close()
server.close()
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log('all steps passed')
